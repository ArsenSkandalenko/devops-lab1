def add_numbers(a: float, b: float) -> float:
    """
    Обчислює суму двох чисел.
    :param a: Перше число
    :param b: Друге число
    :return: Сума чисел
    """
    return a + b

def multiply_numbers(a: float, b: float) -> float:
    """
    Обчислює добуток двох чисел.
    :param a: Перше число
    :param b: Друге число
    :return: Добуток чисел
    """
    return a * b

# Функція для віднімання двох чисел
def subtract_numbers(a, b):
    return a - b